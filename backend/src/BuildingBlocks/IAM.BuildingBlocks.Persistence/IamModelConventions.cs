using System.Text;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace IAM.BuildingBlocks.Persistence;

/// <summary>Shadow audit and concurrency columns present on every IAM table (ADR-0017). Never bound from DTOs.</summary>
public static class AuditColumns
{
    public const string CreatedAtUtc = nameof(CreatedAtUtc);
    public const string CreatedBy = nameof(CreatedBy);
    public const string ModifiedAtUtc = nameof(ModifiedAtUtc);
    public const string ModifiedBy = nameof(ModifiedBy);
    public const string Version = nameof(Version);

    /// <summary>Maximum stored length of an actor identifier.</summary>
    public const int ActorMaxLength = 200;
}

/// <summary>Collations that make code comparison exact and case-sensitive on both engines (ADR-0017, DL-006).</summary>
public static class CodeCollations
{
    public const string SqlServer = "Latin1_General_100_BIN2";
    public const string PostgreSql = "C";

    public static string For(DatabaseProvider provider) => provider switch
    {
        DatabaseProvider.SqlServer => SqlServer,
        DatabaseProvider.PostgreSql => PostgreSql,
        _ => throw new ArgumentOutOfRangeException(nameof(provider)),
    };
}

/// <summary>IAM model conventions applied identically for SQL Server and PostgreSQL.</summary>
public static class IamModelConventions
{
    internal const string CodeAnnotation = "Iam:Code";

    /// <summary>
    /// Marks a string as a code: exact binary comparison (so "01" is not "1" and "ab" is not "AB"), bounded length,
    /// and no leading/trailing spaces or empty value, enforced by a CHECK constraint on both engines.
    /// </summary>
    public static PropertyBuilder<TProperty> IsCode<TProperty>(this PropertyBuilder<TProperty> property, int maxLength)
    {
        ArgumentNullException.ThrowIfNull(property);
        ArgumentOutOfRangeException.ThrowIfLessThan(maxLength, 1);
        if (property.Metadata.ClrType != typeof(string))
        {
            throw new InvalidOperationException($"Only string properties can be codes; {property.Metadata.Name} is {property.Metadata.ClrType.Name}.");
        }

        return property.HasMaxLength(maxLength).HasAnnotation(CodeAnnotation, true);
    }

    /// <summary>Type-level defaults applied before model building.</summary>
    public static void ApplyIamPreConventions(this ModelConfigurationBuilder configurationBuilder)
    {
        ArgumentNullException.ThrowIfNull(configurationBuilder);
        configurationBuilder.Properties<decimal>().HavePrecision(28, 8);
        configurationBuilder.Properties<DateTimeOffset>()
            .HaveConversion<UtcMicrosecondConverter>()
            .HavePrecision(6);
    }

    /// <summary>Conventions applied after the module's own configuration.</summary>
    public static void ApplyIamConventions(this ModelBuilder modelBuilder, DatabaseProvider provider)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(IsTable).ToList())
        {
            var entity = modelBuilder.Entity(entityType.Name);
            entity.Property<DateTimeOffset>(AuditColumns.CreatedAtUtc).IsRequired();
            entity.Property<string>(AuditColumns.CreatedBy).IsRequired().HasMaxLength(AuditColumns.ActorMaxLength);
            entity.Property<DateTimeOffset>(AuditColumns.ModifiedAtUtc).IsRequired();
            entity.Property<string>(AuditColumns.ModifiedBy).IsRequired().HasMaxLength(AuditColumns.ActorMaxLength);
            entity.Property<long>(AuditColumns.Version).IsRequired().IsConcurrencyToken();

            // IDs are generated by the application (UUIDv7, ADR-0016), never by the database.
            foreach (var keyProperty in entityType.FindPrimaryKey()?.Properties ?? [])
            {
                if (keyProperty.ClrType == typeof(Guid))
                {
                    keyProperty.ValueGenerated = ValueGenerated.Never;
                }
            }
        }

        if (provider == DatabaseProvider.PostgreSql)
        {
            ApplySnakeCaseNames(modelBuilder.Model);
        }

        ApplyCodeRules(modelBuilder.Model, provider);
    }

    private static bool IsTable(IMutableEntityType entityType) =>
        !entityType.IsOwned() && entityType.FindPrimaryKey() is not null && entityType.GetTableName() is not null;

    private static void ApplySnakeCaseNames(IMutableModel model)
    {
        foreach (var entityType in model.GetEntityTypes())
        {
            var table = entityType.GetTableName();
            if (table is not null)
            {
                entityType.SetTableName(ToSnakeCase(table));
            }

            foreach (var property in entityType.GetProperties())
            {
                property.SetColumnName(ToSnakeCase(property.GetColumnName()));
            }

            foreach (var key in entityType.GetKeys())
            {
                key.SetName(ToSnakeCase(key.GetName()!));
            }

            foreach (var foreignKey in entityType.GetForeignKeys())
            {
                foreignKey.SetConstraintName(ToSnakeCase(foreignKey.GetConstraintName()!));
            }

            foreach (var index in entityType.GetIndexes())
            {
                index.SetDatabaseName(ToSnakeCase(index.GetDatabaseName()!));
            }
        }
    }

    private static void ApplyCodeRules(IMutableModel model, DatabaseProvider provider)
    {
        foreach (var entityType in model.GetEntityTypes())
        {
            var table = entityType.GetTableName();
            foreach (var property in entityType.GetProperties().Where(p => p.FindAnnotation(CodeAnnotation)?.Value is true))
            {
                property.SetCollation(CodeCollations.For(provider));
                if (table is null)
                {
                    continue;
                }

                var column = property.GetColumnName();
                var name = provider == DatabaseProvider.PostgreSql
                    ? $"ck_{table}_{column}_code"
                    : $"CK_{table}_{column}_Code";

                // Rejects empty values and leading/trailing spaces. SQL Server ignores trailing spaces in comparisons,
                // so without this "AB" and "AB " would collide there but not on PostgreSQL.
                var sql = provider == DatabaseProvider.PostgreSql
                    ? $"\"{column}\" <> '' AND \"{column}\" = btrim(\"{column}\")"
                    : $"DATALENGTH([{column}]) > 0 AND DATALENGTH([{column}]) = DATALENGTH(LTRIM(RTRIM([{column}])))";
                entityType.AddCheckConstraint(name, sql);
            }
        }
    }

    /// <summary>PascalCase / camelCase to snake_case: <c>CreatedAtUtc</c> becomes <c>created_at_utc</c>, <c>PK_Items</c> becomes <c>pk_items</c>.</summary>
    public static string ToSnakeCase(string name)
    {
        ArgumentNullException.ThrowIfNull(name);
        var builder = new StringBuilder(name.Length + 8);
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsUpper(c))
            {
                var previous = i > 0 ? name[i - 1] : '_';
                var next = i + 1 < name.Length ? name[i + 1] : '_';
                var boundary = previous != '_' && (char.IsLower(previous) || char.IsDigit(previous) || (char.IsUpper(previous) && char.IsLower(next)));
                if (boundary)
                {
                    builder.Append('_');
                }

                builder.Append(char.ToLowerInvariant(c));
            }
            else
            {
                builder.Append(c);
            }
        }

        return builder.ToString();
    }
}

/// <summary>
/// Stores <see cref="DateTimeOffset"/> as UTC with microsecond precision on both engines. Non-UTC offsets are rejected
/// rather than silently converted, so a caller bug cannot shift a timestamp (ADR-0017).
/// </summary>
public sealed class UtcMicrosecondConverter : ValueConverter<DateTimeOffset, DateTimeOffset>
{
    public UtcMicrosecondConverter()
        : base(v => ToStore(v), v => FromStore(v))
    {
    }

    public static DateTimeOffset ToStore(DateTimeOffset value)
    {
        if (value.Offset != TimeSpan.Zero)
        {
            throw new ArgumentException("Timestamps must be UTC (offset 00:00) before they are stored (ADR-0017).", nameof(value));
        }

        return TruncateToMicroseconds(value);
    }

    public static DateTimeOffset FromStore(DateTimeOffset value) => value.ToUniversalTime();

    public static DateTimeOffset TruncateToMicroseconds(DateTimeOffset value) =>
        new(value.UtcTicks - (value.UtcTicks % 10), TimeSpan.Zero);
}
