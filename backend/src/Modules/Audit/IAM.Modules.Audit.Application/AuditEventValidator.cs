using System.Buffers;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using IAM.Modules.Audit.Contracts;

namespace IAM.Modules.Audit.Application;

/// <summary>A record that passed validation, with the masked canonical payload and the whole-row checksum (ADR-0018).</summary>
public sealed record ValidatedAuditEvent(
    Guid Id,
    DateTimeOffset RecordedAtUtc,
    DateTimeOffset OccurredAtUtc,
    string ActorId,
    string? EffectiveActorId,
    string Action,
    string TargetType,
    string? TargetId,
    string Outcome,
    string? Reason,
    string CorrelationId,
    string? CausationId,
    string? PolicyVersionRef,
    string? PolicyVersionHash,
    string PayloadCanonical,
    int SchemaVersion)
{
    /// <summary>
    /// Lower-case hex SHA-256 over every stored field except the database-assigned <c>Seq</c>
    /// (see <see cref="AuditEventValidator.ComputeRowHash"/>). Unkeyed: an integrity checksum, not tamper-proofing.
    /// </summary>
    public string RowHash { get; init; } = string.Empty;
}

/// <summary>
/// Validates audit records before anything is written. Every field is bounded, codes must match strict patterns,
/// actions must be registered, control and invisible formatting characters are refused (no log or report spoofing),
/// names that suggest secrets are refused, credential-shaped values are refused in every free-text field, and sensitive
/// values are masked <b>before</b> hashing, because a hashed value cannot be redacted later.
/// </summary>
public static partial class AuditEventValidator
{
    public const int ActionMaxLength = 100;
    public const int TargetTypeMaxLength = 100;
    public const int TargetIdMaxLength = 200;
    public const int ActorMaxLength = 200;
    public const int ReasonMaxLength = 1000;
    public const int CorrelationIdMaxLength = 100;
    public const int PolicyVersionRefMaxLength = 200;
    public const int HashLength = 64;
    public const int OutcomeMaxLength = 20;
    public const int MaxPayloadFields = 64;
    public const int PayloadValueMaxLength = 2000;
    public const int PayloadCanonicalMaxLength = 16384;
    public const int MaxSchemaVersion = 1000;

    /// <summary>Version of the row-hash layout, part of the hashed text so the layout can change later.</summary>
    public const string RowHashLayout = "iam.audit.row.v1";

    /// <summary>Stored in place of a sensitive value.</summary>
    public const string MaskedValue = "[masked]";

    /// <summary>How far in the future <see cref="AuditEventRecord.OccurredAtUtc"/> may be, to allow for clock skew.</summary>
    public static readonly TimeSpan MaxClockSkew = TimeSpan.FromMinutes(5);

    /// <summary>Matched against the field name with '.', '_' and '-' removed, lower-cased.</summary>
    private static readonly string[] SecretNameFragments =
    [
        "password", "passwd", "pwd", "passphrase", "secret", "token", "credential", "apikey", "privatekey",
        "signingkey", "accountkey", "sharedaccesskey", "authorization", "bearer", "assertion", "cookie", "sessionid",
        "connectionstring",
    ];

    /// <summary>Short names that are secrets on their own but too common as substrings to match by fragment.</summary>
    private static readonly HashSet<string> SecretNames = new(StringComparer.Ordinal) { "pin", "otp", "totp", "hotp", "cvv", "sig" };

    /// <summary>Validates <paramref name="record"/> and returns the row to store. Throws <see cref="AuditRecordRejectedException"/>.</summary>
    public static ValidatedAuditEvent Validate(
        AuditEventRecord record,
        string? actorId,
        IReadOnlySet<string> registeredActions,
        Guid eventId,
        DateTimeOffset recordedAtUtc)
    {
        ArgumentNullException.ThrowIfNull(record);
        ArgumentNullException.ThrowIfNull(registeredActions);
        if (recordedAtUtc.Offset != TimeSpan.Zero)
        {
            throw new ArgumentException("The recording time must be UTC.", nameof(recordedAtUtc));
        }

        if (eventId == Guid.Empty)
        {
            throw new ArgumentException("The event identifier must be generated by the application.", nameof(eventId));
        }

        var actor = RequiredText(actorId, "ActorId", ActorMaxLength);
        var action = Code(record.Action, "Action", ActionMaxLength, DottedCodePattern(), required: true)!;
        if (!registeredActions.Contains(action))
        {
            throw new AuditRecordRejectedException("Action", "is not a registered audit action");
        }

        var targetType = Code(record.TargetType, "TargetType", TargetTypeMaxLength, DottedCodePattern(), required: true)!;
        var outcome = record.Outcome switch
        {
            AuditOutcome.Succeeded => "Succeeded",
            AuditOutcome.Denied => "Denied",
            AuditOutcome.Failed => "Failed",
            _ => throw new AuditRecordRejectedException("Outcome", "is not a defined outcome"),
        };

        if (record.OccurredAtUtc.Offset != TimeSpan.Zero)
        {
            throw new AuditRecordRejectedException("OccurredAtUtc", "must be UTC");
        }

        if (record.OccurredAtUtc == default || record.OccurredAtUtc > recordedAtUtc + MaxClockSkew)
        {
            throw new AuditRecordRejectedException("OccurredAtUtc", "must be set and not in the future");
        }

        if (record.SchemaVersion is < 1 or > MaxSchemaVersion)
        {
            throw new AuditRecordRejectedException("SchemaVersion", $"must be between 1 and {MaxSchemaVersion}");
        }

        var row = new ValidatedAuditEvent(
            eventId,
            recordedAtUtc,
            Microseconds(record.OccurredAtUtc),
            actor,
            FreeText(record.EffectiveActorId, "EffectiveActorId", ActorMaxLength),
            action,
            targetType,
            FreeText(record.TargetId, "TargetId", TargetIdMaxLength),
            outcome,
            FreeText(record.Reason, "Reason", ReasonMaxLength, allowLineBreaks: true),
            Code(record.CorrelationId, "CorrelationId", CorrelationIdMaxLength, CorrelationPattern(), required: true)!,
            Code(record.CausationId, "CausationId", CorrelationIdMaxLength, CorrelationPattern(), required: false),
            FreeText(record.PolicyVersionRef, "PolicyVersionRef", PolicyVersionRefMaxLength),
            Code(record.PolicyVersionHash, "PolicyVersionHash", HashLength, HashPattern(), required: false),
            CanonicalPayload(record.Payload),
            record.SchemaVersion);
        return row with { RowHash = ComputeRowHash(row) };
    }

    /// <summary>
    /// Lower-case hex SHA-256 of the canonical row: a JSON array of <see cref="RowHashLayout"/> followed by every stored
    /// field except <c>Seq</c>, in a fixed order. GUIDs are lower-case "D" format; timestamps are UTC
    /// <c>yyyy-MM-ddTHH:mm:ss.ffffffZ</c>; absent values are JSON null. Readers can recompute it from the stored columns.
    /// </summary>
    public static string ComputeRowHash(ValidatedAuditEvent row)
    {
        ArgumentNullException.ThrowIfNull(row);
        var buffer = new ArrayBufferWriter<byte>();
        using (var writer = new Utf8JsonWriter(buffer, new JsonWriterOptions { Indented = false }))
        {
            writer.WriteStartArray();
            writer.WriteStringValue(RowHashLayout);
            writer.WriteStringValue(row.Id.ToString("D"));
            writer.WriteStringValue(Timestamp(row.RecordedAtUtc));
            writer.WriteStringValue(Timestamp(row.OccurredAtUtc));
            writer.WriteStringValue(row.ActorId);
            writer.WriteStringValue(row.EffectiveActorId);
            writer.WriteStringValue(row.Action);
            writer.WriteStringValue(row.TargetType);
            writer.WriteStringValue(row.TargetId);
            writer.WriteStringValue(row.Outcome);
            writer.WriteStringValue(row.Reason);
            writer.WriteStringValue(row.CorrelationId);
            writer.WriteStringValue(row.CausationId);
            writer.WriteStringValue(row.PolicyVersionRef);
            writer.WriteStringValue(row.PolicyVersionHash);
            writer.WriteStringValue(row.PayloadCanonical);
            writer.WriteNumberValue(row.SchemaVersion);
            writer.WriteEndArray();
        }

        return Convert.ToHexStringLower(SHA256.HashData(buffer.WrittenSpan));
    }

    /// <summary>True if <paramref name="action"/> is a well-formed action code (used when modules register actions).</summary>
    public static bool IsValidActionCode(string? action) =>
        action is { Length: > 0 and <= ActionMaxLength } && DottedCodePattern().IsMatch(action);

    private static string CanonicalPayload(IReadOnlyList<AuditPayloadField>? payload)
    {
        payload ??= [];
        if (payload.Count > MaxPayloadFields)
        {
            throw new AuditRecordRejectedException("Payload", $"has more than {MaxPayloadFields} fields");
        }

        var fields = new SortedDictionary<string, string?>(StringComparer.Ordinal);
        foreach (var field in payload)
        {
            if (field is null || field.Name is null || !PayloadNamePattern().IsMatch(field.Name))
            {
                throw new AuditRecordRejectedException("Payload", "has a field name that is not allowed");
            }

            if (LooksLikeSecretName(field.Name))
            {
                throw new AuditRecordRejectedException($"Payload.{field.Name}", "looks like a secret and must not be audited");
            }

            var value = field.Classification switch
            {
                AuditFieldClass.Sensitive => field.Value is null ? null : MaskedValue,
                AuditFieldClass.Plain => FreeText(field.Value, $"Payload.{field.Name}", PayloadValueMaxLength, allowBlank: true),
                _ => throw new AuditRecordRejectedException($"Payload.{field.Name}", "has an undefined classification"),
            };

            if (!fields.TryAdd(field.Name, value))
            {
                throw new AuditRecordRejectedException($"Payload.{field.Name}", "appears more than once");
            }
        }

        var buffer = new ArrayBufferWriter<byte>();
        using (var writer = new Utf8JsonWriter(buffer, new JsonWriterOptions { Indented = false }))
        {
            writer.WriteStartObject();
            foreach (var (name, value) in fields)
            {
                writer.WriteString(name, value);
            }

            writer.WriteEndObject();
        }

        var canonical = Encoding.UTF8.GetString(buffer.WrittenSpan);
        return canonical.Length > PayloadCanonicalMaxLength
            ? throw new AuditRecordRejectedException("Payload", $"is longer than {PayloadCanonicalMaxLength} characters")
            : canonical;
    }

    private static bool LooksLikeSecretName(string name)
    {
        var normalized = name.Replace(".", string.Empty, StringComparison.Ordinal)
            .Replace("_", string.Empty, StringComparison.Ordinal)
            .ToLowerInvariant();
        var lastSegment = name.Split('.', '_')[^1].ToLowerInvariant();
        return SecretNameFragments.Any(f => normalized.Contains(f, StringComparison.Ordinal))
            || SecretNames.Contains(normalized)
            || SecretNames.Contains(lastSegment);
    }

    private static bool LooksLikeCredential(string value) =>
        JwtPattern().IsMatch(value)
        || value.Contains("-----BEGIN", StringComparison.Ordinal)
        || AuthorizationValuePattern().IsMatch(value)
        || KeyValueSecretPattern().IsMatch(value)
        || AwsAccessKeyPattern().IsMatch(value);

    private static string RequiredText(string? value, string field, int maxLength) =>
        FreeText(value, field, maxLength) ?? throw new AuditRecordRejectedException(field, "is required");

    /// <summary>Bounded text with no control or invisible formatting characters and nothing that looks like a credential.</summary>
    private static string? FreeText(string? value, string field, int maxLength, bool allowBlank = false, bool allowLineBreaks = false)
    {
        if (value is null)
        {
            return null;
        }

        if (!allowBlank && string.IsNullOrWhiteSpace(value))
        {
            throw new AuditRecordRejectedException(field, "must not be blank");
        }

        if (value.Length > maxLength)
        {
            throw new AuditRecordRejectedException(field, $"is longer than {maxLength} characters");
        }

        if (value.Any(c => IsForbiddenCharacter(c, allowLineBreaks)) || !IsWellFormedUtf16(value))
        {
            throw new AuditRecordRejectedException(field, "contains control characters, invisible formatting characters or malformed text");
        }

        if (LooksLikeCredential(value))
        {
            throw new AuditRecordRejectedException(field, "looks like a token, key or password and must not be audited");
        }

        return value;
    }

    /// <summary>
    /// Control characters (except CR/LF where allowed), Unicode format characters (bidi overrides, zero-width and
    /// similar invisible characters) and line/paragraph separators.
    /// </summary>
    private static bool IsForbiddenCharacter(char c, bool allowLineBreaks)
    {
        if (char.IsControl(c))
        {
            return !(allowLineBreaks && c is '\n' or '\r');
        }

        return char.GetUnicodeCategory(c) is UnicodeCategory.Format or UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator;
    }

    private static string? Code(string? value, string field, int maxLength, Regex pattern, bool required)
    {
        if (value is null)
        {
            return required ? throw new AuditRecordRejectedException(field, "is required") : null;
        }

        if (value.Length > maxLength || !pattern.IsMatch(value))
        {
            throw new AuditRecordRejectedException(field, "is not a valid code");
        }

        return value;
    }

    private static bool IsWellFormedUtf16(string value)
    {
        for (var i = 0; i < value.Length; i++)
        {
            if (char.IsHighSurrogate(value[i]))
            {
                if (i + 1 >= value.Length || !char.IsLowSurrogate(value[i + 1]))
                {
                    return false;
                }

                i++;
            }
            else if (char.IsLowSurrogate(value[i]))
            {
                return false;
            }
        }

        return true;
    }

    private static string Timestamp(DateTimeOffset value) =>
        value.UtcDateTime.ToString("yyyy-MM-dd'T'HH:mm:ss.ffffff'Z'", CultureInfo.InvariantCulture);

    private static DateTimeOffset Microseconds(DateTimeOffset value) =>
        new(value.UtcTicks - (value.UtcTicks % 10), TimeSpan.Zero);

    /// <summary>Lower-case dotted code with at least two segments: <c>identity.session.started</c>.</summary>
    [GeneratedRegex(@"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex DottedCodePattern();

    [GeneratedRegex(@"^[A-Za-z0-9._:\-]+$", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex CorrelationPattern();

    [GeneratedRegex("^[0-9a-f]{64}$", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex HashPattern();

    [GeneratedRegex(@"^[A-Za-z][A-Za-z0-9_.]{0,63}$", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex PayloadNamePattern();

    [GeneratedRegex(@"eyJ[A-Za-z0-9_\-]{8,}\.[A-Za-z0-9_\-]{8,}\.", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex JwtPattern();

    /// <summary><c>Bearer</c>/<c>Basic</c> followed by a token-like value, anywhere in the text.</summary>
    [GeneratedRegex(@"(?i)\b(bearer|basic)\s+[A-Za-z0-9._~+/=\-]{12,}", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex AuthorizationValuePattern();

    /// <summary>Connection-string and URL secrets: <c>Password=</c>, <c>Pwd=</c>, <c>AccountKey=</c>, <c>SharedAccessKey=</c>, SAS <c>sig=</c>.</summary>
    [GeneratedRegex(@"(?i)(\b(password|pwd|accountkey|sharedaccesskey)\s*=)|([?&]sig=)", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex KeyValueSecretPattern();

    [GeneratedRegex(@"\b(AKIA|ASIA)[0-9A-Z]{16}\b", RegexOptions.CultureInvariant, matchTimeoutMilliseconds: 100)]
    private static partial Regex AwsAccessKeyPattern();
}
